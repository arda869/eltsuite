import assert from 'node:assert/strict';
import { initializeApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { requestDeletion, processDeletion } from './service.js';
if (!process.env.FIRESTORE_EMULATOR_HOST) throw Error('Firestore emulator required');
initializeApp({ projectId: 'demo-account-deletion' });
const db = getFirestore(), now = Math.floor(Date.now()/1000);
const login = uid => ({uid, token:{email:uid+'@example.com',email_verified:true,auth_time:now}});
const identitiesMap = new Map(['teacher','other','learner','trainee','admin','owner'].map(uid=>[uid,{uid,email:uid==='owner'?'ardanurioglu@gmail.com':uid+'@example.com'}]));
const deleted = [], realRemoved = [];
const identities = {getUser:async uid=>identitiesMap.get(uid),updateUser:async()=>{},revokeRefreshTokens:async()=>{},deleteUser:async uid=>{deleted.push(uid);identitiesMap.delete(uid);}};
const realtime = {ref:path=>({remove:async()=>realRemoved.push(path)})};
for(const uid of ['teacher','other','trainee'])await db.doc('users/'+uid).set({role:'teacher'});
await db.doc('users/learner').set({role:'learner',classId:'owned'});
await db.doc('superAdmins/admin@example.com').set({});
await db.doc('classes/owned').set({teacherId:'teacher',classCode:'OWN'});
await db.doc('classes/owned/learners/l').set({authUid:'learner'});
await db.doc('classes/owned/learners/t').set({authUid:'trainee',teacherUid:'trainee'});
await db.doc('classes/owned/items/i/tasks/t/versions/v').set({content:'private'});
await db.doc('classCodes/OWN').set({teacherId:'teacher'});
await db.doc('classes/elsewhere').set({teacherId:'other',teacherIds:['other','teacher'],coTeachers:{teacher:{role:'co'}}});
await db.doc('sharedDocs/mine').set({owner:'teacher',docKey:'owned.doc'});
await db.doc('sharedDocs/theirs').set({owner:'other'});
await db.doc('users/teacher/media/m').set({data:'bytes'});
await db.doc('teachingCoach/teacher/conversations/c/turns/t').set({text:'private'});
const submit=(auth,uid='teacher',confirmation='DELETE')=>requestDeletion(db,identities,auth,{uid,confirmation});
await assert.rejects(submit(null));
await assert.rejects(submit(login('other')));
await assert.rejects(submit({...login('teacher'),token:{...login('teacher').token,proxyBy:'admin'}}));
await assert.rejects(submit({...login('teacher'),token:{...login('teacher').token,auth_time:now-600}}));
await assert.rejects(submit(login('teacher'),'teacher',''));
await assert.rejects(submit(login('admin'),'owner'));
await assert.rejects(submit(login('admin'),'admin'));
assert.equal((await db.doc('classes/owned').get()).exists,true);
await db.doc('orgs/o').set({adminEmails:['teacher@example.com'],teachers:{teacher:{}}});
await assert.rejects(submit(login('teacher')));
await db.doc('orgs/o').update({adminEmails:['teacher@example.com','other@example.com']});
assert.equal((await submit(login('teacher'))).accepted,true);
assert.equal((await db.doc('accounts/teacher').get()).get('suspended'),true);
// Inject an interruption; a new attempt must resume rather than report success.
await assert.rejects(processDeletion(db,{...identities,updateUser:async()=>{throw Error('transient');}},realtime,'teacher'));
assert.equal((await db.doc('accountDeletions/teacher').get()).get('status'),'pending');
await processDeletion(db,identities,realtime,'teacher');
assert.equal((await db.doc('accountDeletions/teacher').get()).get('status'),'complete');
assert.deepEqual(deleted.sort(),['learner','teacher']);
for(const path of ['users/teacher','users/teacher/media/m','classes/owned','classes/owned/items/i/tasks/t/versions/v','classCodes/OWN','sharedDocs/mine','teachingCoach/teacher/conversations/c/turns/t'])assert.equal((await db.doc(path).get()).exists,false,path);
for(const path of ['users/trainee','users/other','classes/elsewhere','sharedDocs/theirs'])assert.equal((await db.doc(path).get()).exists,true,path);
assert.equal((await db.doc('classes/elsewhere').get()).get('coTeachers.teacher'),undefined);
assert.deepEqual((await db.doc('orgs/o').get()).get('adminEmails'),['other@example.com']);
assert.ok(realRemoved.includes('collab/owned_doc'));
await processDeletion(db,identities,realtime,'teacher');
assert.equal(deleted.length,2);
assert.equal((await submit(login('admin'),'other')).accepted,true);
console.log('PASS: real Firestore cleanup and retry; simulated Auth/Realtime adapters; self/admin access, stale sign-in, preview, owner/super-admin protection, organisation admin guard, recursive cleanup, retained unrelated classes and training teachers.');
