import assert from 'node:assert/strict';
import {initializeApp} from 'firebase-admin/app';
import {getFirestore} from 'firebase-admin/firestore';
import {handleObservation,observationCoachEvidence} from './service.js';
if(!process.env.FIRESTORE_EMULATOR_HOST)throw Error('Firestore emulator required.');
initializeApp({projectId:'demo-observation'});const db=getFirestore();
const auth=uid=>({uid,token:{email:uid+'@example.com'}}),call=(uid,action,data={})=>handleObservation(db,auth(uid),{action,...data});
for(const uid of ['teacher','other','admin'])await db.doc('users/'+uid).set({role:'teacher'});
