for(const uid of ['other','admin','learner'])await assert.rejects(call(uid,'load',{id:'baseline'}));
await assert.rejects(handleObservation(db,{...auth('teacher'),token:{proxyBy:'admin'}},{action:'list'}));
const note={kind:'observed',offsetSeconds:30,text:'Four learners volunteered.'},save={id:'baseline',noteId:'one',version:0,note};
